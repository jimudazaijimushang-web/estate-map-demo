const entries = Object.entries(translations).sort((a, b) => b[0].length - a[0].length);
const pattern = new RegExp(entries.map(([key]) => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const originals = new WeakMap();
const attributes = ['title', 'aria-label', 'placeholder'];
let language = 'zh-CN';
try { language = localStorage.getItem('nexus-language') === 'en' ? 'en' : 'zh-CN'; } catch {}
export const getLanguage = () => language;
export const translate = (text) => language === 'en' ? text.replace(pattern, (key) => translations[key]) : text;
function applyValue(node, key, value, write) {
  const records = originals.get(node) || new Map();
  const previous = records.get(key);
  const source = previous && previous.output === value ? previous.source : value;
  const output = translate(source);
  records.set(key, { source, output });
  originals.set(node, records);
  if (value !== output) write(output);
}
function applyNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (node.parentElement?.closest('script, style, textarea, option, [contenteditable]')) return;
    applyValue(node, 'text', node.nodeValue || '', (value) => { node.nodeValue = value; });
  } else if (node instanceof Element) {
    for (const attribute of attributes) {
      const value = node.getAttribute(attribute);
      if (value !== null) applyValue(node, attribute, value, (text) => node.setAttribute(attribute, text));
    }
    node.childNodes.forEach(applyNode);
  }
}
export function setLanguage(value) {
  language = value === 'en' ? 'en' : 'zh-CN';
  try { localStorage.setItem('nexus-language', language); } catch {}
  document.documentElement.lang = language;
  applyNode(document.documentElement);
}
export function startTranslations() {
  setLanguage(language);
  new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'childList') record.addedNodes.forEach(applyNode);
      else applyNode(record.target);
    }
  }).observe(document.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: attributes });
}
